-- MOSTRAR BANCO DE DADOS
SHOW DATABASES;

-- 2. CRIAR BANCO DE DADOS:
CREATE DATABASE NOME_DO_BANCO;

-- 3. USAR UM BANCO DE DADOS;
USE NOME_DO_BANCO;

-- 4 MOSTRAR TABELAS
SHOW TABLES;

-- 5. CRIAR TABELA
CREATE TABLE NOME_DA_TABELA
(
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(100),
    idade INT
);

-- 6. INSERIR DADOS EM UMA TABELA:
INSERT INTO NOME_DA_TABELA (nome, idade) VALUES ('JOAO', 30);

-- 7. SELECIONAR DADOS DE UMA TABELA:
SELECT * FROM NOME_DA_TABELA;

-- 8. ATUALIZAR DADOS DE UMA TABELA:
UPDATE NOME_DA_TABELA SET idade = 31 WHERE nome = JOAO;

--9. DELETAR DADOS DE UMA TABELA:
DELETE FROM NOME_DA_TABELA WHERE nome = 'JOAO';

-- 10. DELETAR TABELA:
DROP TABLE NOME_DA_TABELA;

-- 11. DELETAR DATABASE:
DROP DATABASE NOME_DO_BANCO;