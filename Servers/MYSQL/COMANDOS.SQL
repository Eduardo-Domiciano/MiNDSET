-- COMANDOS BASICOS DE MYSQL PARA TREINAR SEM WORKBENCH;

-- 1. CONECTAR AO MYSQL:
--mysql -u usuario -p e depois digitar a senha

-- 2. STATUS DO MYSQL:
STATUS

-- 3. MOSTRAR BANCO DE DADOS
SHOW DATABASES;

-- 4. CRIAR BANCO DE DADOS:
CREATE DATABASE NOME_DO_BANCO;

-- 5. USAR UM BANCO DE DADOS;
USE NOME_DO_BANCO;

-- 6 MOSTRAR TABELAS
SHOW TABLES;

-- 7. VER CAMPOS DA TABELA:
DESCRIBE PESSOAS;

-- 8. CRIAR TABELA
CREATE TABLE NOME_DA_TABELA
(
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(100),
    idade INT
);

-- 9. INSERIR DADOS EM UMA TABELA:
INSERT INTO NOME_DA_TABELA (nome, idade) VALUES ('JOAO', 30);

-- 10. SELECIONAR DADOS DE UMA TABELA:
SELECT * FROM NOME_DA_TABELA;

-- 11. ATUALIZAR DADOS DE UMA TABELA:
UPDATE NOME_DA_TABELA SET idade = 31 WHERE nome = JOAO;

--12. DELETAR DADOS DE UMA TABELA:
DELETE FROM NOME_DA_TABELA WHERE nome = 'JOAO';

-- 13. DELETAR TABELA:
DROP TABLE NOME_DA_TABELA;

-- 14. DELETAR DATABASE:
DROP DATABASE NOME_DO_BANCO;

-- 15. Atualizar o MySql:
sudo apt-get upgrade mysql-server
-- Se não funcionar, vc também pode usar
sudo apt-get install mysql-server



